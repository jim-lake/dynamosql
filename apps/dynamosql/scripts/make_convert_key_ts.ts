import { writeFileSync } from 'fs';
import { join } from 'path';
import { format, resolveConfig } from 'prettier';

import type { HashUniqueKeyType } from '../src/lib/helpers/hash_unique_index';
import type { ValueType } from '../src/lib/types/value_type';

type Conversion = [ValueType, HashUniqueKeyType, string];
type LabeledConversion = [string, string];

const HARDCODED_MAX_KEYS = 2;
const HELPERS_DIR = join(__dirname, '..', 'src', 'lib', 'helpers');
const GENERATOR_PATH = 'scripts/make_convert_key_ts.ts';

const CONVERSIONS: Conversion[] = [
  ['null', 'string', 'null'],
  ['string', 'string', '$v as string'],
  ['string', 'string_ci', '$v as string'],
  ['char', 'string', '$v as string'],
  ['char', 'string_ci', '$v as string'],
  ['text', 'string', '$v as string'],
  ['text', 'string_ci', '$v as string'],
  ['json', 'string', '$v as string'],
  ['bool', 'number', 'Number($v)'],
  ['long', 'number', '$v as number'],
  ['year', 'number', '$v as number'],
  ['number', 'number', '$v as number'],
  ['double', 'number', '$v as number'],
  ['longlong', 'bigint', 'BigInt($v as number | bigint)'],
  ['interval', 'number', '($v as SQLInterval).getNumber()'],
  ['datetime', 'number', '($v as SQLDateTime).toNumber()'],
  ['date', 'number', '($v as SQLDate).toNumber()'],
  ['time', 'number', '($v as SQLTime).toNumber()'],
  ['buffer', 'buffer', '$v as Buffer'],
];

const VARIANTS: {
  file: string;
  nullable: boolean;
  conversions: Conversion[];
}[] = [
  {
    file: 'convert_key.ts',
    nullable: false,
    conversions: CONVERSIONS.filter(([valueType]) => valueType !== 'null'),
  },
  { file: 'convert_key_nullable.ts', nullable: true, conversions: CONVERSIONS },
];

function combinations(
  singles: LabeledConversion[],
  length: number
): LabeledConversion[][] {
  if (length === 0) {
    return [[]];
  }
  return combinations(singles, length - 1).flatMap((prefix) =>
    singles.map((single) => [...prefix, single])
  );
}

function groupCases(entries: [string, string][]): string[] {
  const labelsByBody = new Map<string, string[]>();
  for (const [label, body] of entries) {
    labelsByBody.set(body, [...(labelsByBody.get(body) ?? []), label]);
  }
  return [...labelsByBody].flatMap(([body, labels]) => [
    ...labels.map((label) => `case '${label}':`),
    body,
  ]);
}

async function main(): Promise<void> {
  for (const { file, nullable, conversions } of VARIANTS) {
    const outputPath = join(HELPERS_DIR, file);
    const singles: LabeledConversion[] = conversions.map(
      ([valueType, keyType, expression]): LabeledConversion => [
        `${valueType}:${keyType}`,
        expression,
      ]
    );
    const keyValue = nullable
      ? 'OrderedNullableKeyValue'
      : 'HashUniqueKeyValue';
    const convertKeyFunction = nullable
      ? 'ConvertKeyNullableFunction'
      : 'ConvertKeyFunction';

    const genericCases = groupCases(
      singles.map(([label, expression]): [string, string] => {
        const param = expression.includes('$v') ? '(value: unknown)' : '()';
        return [
          label,
          `return ${param} => ${expression.replaceAll('$v', 'value')};`,
        ];
      })
    );

    const hardcodedCases = groupCases(
      Array.from({ length: HARDCODED_MAX_KEYS }, (_, i) => i + 1).flatMap(
        (length) =>
          combinations(singles, length).map((combo): [string, string] => {
            const expressions = combo.map(([, expression], i) =>
              expression.replaceAll('$v', `cells[${i}].value`)
            );
            const body = combo.some(([, expression]) =>
              expression.includes('$v')
            )
              ? `return ((cells: [${combo.map(() => 'CellValue').join(', ')}]) => [${expressions.join(', ')}]) as ${convertKeyFunction};`
              : `return () => [${expressions.join(', ')}];`;
            return [combo.map(([label]) => label).join(','), body];
          })
      )
    );

    const keyImports = nullable
      ? [
          "import type { HashUniqueKeyType } from './hash_unique_index';",
          "import type { OrderedNullableKeyValue } from './ordered_nullable_index';",
        ]
      : [
          "import type { HashUniqueKeyType, HashUniqueKeyValue } from './hash_unique_index';",
        ];
    const nonNullAssumption = nullable
      ? []
      : [
          '// Untested assumption: key values are never null. A null column type throws here.',
        ];

    const lines = [
      `// Generated by ${GENERATOR_PATH}. Do not edit.`,
      "import type { CellValue, ColumnDef } from '../engine';",
      ...keyImports,
      "import type { SQLDate } from '../types/sql_date';",
      "import type { SQLDateTime } from '../types/sql_datetime';",
      "import type { SQLInterval } from '../types/sql_interval';",
      "import type { SQLTime } from '../types/sql_time';",
      '',
      `type Converter = (value: unknown) => ${keyValue};`,
      `export type ${convertKeyFunction} = (cells: CellValue[]) => ${keyValue}[];`,
      '',
      ...nonNullAssumption,
      `export function ${nullable ? 'createConvertKeyNullable' : 'createConvertKey'}(columns: ColumnDef[], types: HashUniqueKeyType[]): ${convertKeyFunction} {`,
      `if (types.length > ${HARDCODED_MAX_KEYS}) {`,
      'const kinds = types.slice();',
      'const converters = columns.map((column, i): Converter => {',
      'switch (`${column.type}:${kinds[i]}`) {',
      ...genericCases,
      '}',
      'throw new Error(`Unsupported key conversion: ${column.type}:${kinds[i]}`);',
      '});',
      'return (cells) => cells.map((cell, i) => (converters[i] as Converter)(cell.value));',
      '}',
      "switch (columns.map((column, i) => `${column.type}:${types[i]}`).join(',')) {",
      ...hardcodedCases,
      '}',
      "throw new Error(`Unsupported key conversion: ${types.join(',')}`);",
      '}',
    ].join('\n');

    const config = await resolveConfig(outputPath);
    const formatted = await format(lines + '\n', {
      ...config,
      filepath: outputPath,
    });
    writeFileSync(outputPath, formatted);
    console.log(`Wrote ${outputPath}`);
  }
}

main();
