-- TIME(n) values from a derived table compare at their stored precision
CREATE DATABASE IF NOT EXISTS der_time;
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t = '10:00:00.0099';
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE '10:00:00.0099' = t;
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t = '10:00:00.01';
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t <=> '10:00:00.0099';
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t = '10:00:00.02';
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t IN ('10:00:00.0099');
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t > '10:00:00.0099';
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t < '10:00:00.0099';
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t BETWEEN '10:00:00.00' AND '10:00:00.0099';
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t = CAST('10:00:00.0099' AS TIME(2));
SELECT t FROM (SELECT CAST('10:00:00.0099' AS TIME(2)) AS t) s WHERE t = '10:00:00';
DROP DATABASE der_time;
