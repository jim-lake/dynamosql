CREATE DATABASE IF NOT EXISTS mem_ctas;
USE mem_ctas;
DROP TEMPORARY TABLE IF EXISTS src, dsrc, cd, c1, c2, c3, c4, c5, c6, c7;
DROP TABLE IF EXISTS p1, p2;
CREATE TEMPORARY TABLE src (id INT PRIMARY KEY, v VARCHAR(10) NOT NULL, d DECIMAL(5,2), dt DATETIME, n BIGINT);
CREATE TEMPORARY TABLE dsrc (id INT PRIMARY KEY, k INT NOT NULL DEFAULT 5, s VARCHAR(5) DEFAULT 'zz');
