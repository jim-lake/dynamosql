CREATE TEMPORARY TABLE c1 ENGINE=MEMORY AS SELECT * FROM src;
SELECT * FROM c1 ORDER BY id;
SHOW CREATE TABLE c1;

CREATE TEMPORARY TABLE c2 (pk INT PRIMARY KEY) ENGINE=MEMORY AS SELECT id AS pk, v FROM src WHERE id > 1;
SELECT * FROM c2 ORDER BY pk;
