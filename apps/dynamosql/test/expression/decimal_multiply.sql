-- DECIMAL * DECIMAL is exact, with the scale equal to the sum of operand scales
SELECT CAST(42.225 AS DECIMAL(10,2)) * 10 AS r;
SELECT CAST(42.225 AS DECIMAL(10,2)) * CAST(2.5 AS DECIMAL(5,1)) AS r;
SELECT 1.5 * 2.25 AS r;
SELECT 0.1 * 3 AS r;
SELECT 0.1 * 0.1 AS r;
SELECT -1.25 * 4 AS r;
SELECT -1.25 * -4.5 AS r;
SELECT 2 * 3.10 AS r;
SELECT 3.10 * 2 AS r;
SELECT CAST(-7.5 AS DECIMAL(5,1)) * CAST(0.25 AS DECIMAL(4,2)) AS r;
SELECT CAST(1.50 AS DECIMAL(5,2)) * CAST(2.000 AS DECIMAL(6,3)) AS r;
SELECT 0.5 * 0 AS r;
SELECT 1234.5678 * 1000 AS r;
SELECT 99999.99 * 99999.99 AS r;
