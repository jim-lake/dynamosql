export function tertiaryTree(
  secondary: number,
  context: number
): TertiaryTree | undefined {
  if (secondary === 0x20) return standardSecondaryTrees[context];
  const index = secondaryTreeIndex.get(secondary);
  return index === undefined ? undefined : trees[index];
}
