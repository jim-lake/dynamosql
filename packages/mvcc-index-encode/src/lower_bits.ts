const trees: TertiaryTree[] = treeEntries.map((entries) => {
  const lengths = new Uint8Array(32);
  const codes = new Uint16Array(32);
  for (const [unit, token] of entries) {
    lengths[unit] = token.length;
    codes[unit] = parseInt(token, 2);
  }
  return { lengths, codes };
});

