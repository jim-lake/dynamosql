let nextSecondary = 0;
let lastWidth = 0;
for (const [first, last, width] of secondaryRuns) {
  nextSecondary *= 2 ** (width - lastWidth);
  for (let unit = first; unit <= last; unit++) {
    secondaryCodes[unit] = nextSecondary++;
    secondaryLengths[unit] = width;
  }
  lastWidth = width;
}
export { secondaryLengths };

export const tertiaryContexts: readonly number[] = [0, 26, 28, 4, 2];

export function tertiaryContext(unit: number): number {
  const index = tertiaryContexts.indexOf(unit);
  return index < 0 ? 0 : index;
}

